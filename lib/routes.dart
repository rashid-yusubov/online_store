/// Класс констант именованных маршрутов (Named Routes).
/// 
/// Вынесение строк маршрутов в отдельный класс предотвращает опечатки в путях
/// и централизует управление навигацией приложения в одном месте.
class Routes {
  /// Стартовый маршрут: Экран заставки (Splash Screen).
  static const loading = '/';

  /// Маршрут экрана авторизации пользователя.
  static const login = '/login';

  /// Маршрут экрана регистрации нового пользователя.
  static const register = '/register';

  /// Маршрут главного экрана (Каталог и нижняя панель NavigationBar).
  static const home = '/home';

  /// Маршрут экрана детализации выбранного пункта каталога.
  static const detail = '/detail';

  /// Маршрут экрана профиля пользователя (для прямого перехода).
  static const profile = '/profile';
}
